#!/usr/bin/env python3
"""Validate card artwork filenames and generate the Vite import map."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CARD_SOURCE = ROOT / "src" / "data" / "cards.js"
ART_DIRECTORY = ROOT / "src" / "assets" / "card-art"
GENERATED_MODULE = ROOT / "src" / "data" / "card-art.generated.js"
ALLOWED_EXTENSIONS = {".avif", ".jpeg", ".jpg", ".png", ".webp"}
CARD_ID_PATTERN = re.compile(r'^\s{2}"([A-Z][A-Z0-9-]+)":\s*\{', re.MULTILINE)
SAFE_STEM_PATTERN = re.compile(r"^[A-Z][A-Z0-9-]+$")


def library_ids() -> set[str]:
    source = CARD_SOURCE.read_text(encoding="utf-8")
    ids = set(CARD_ID_PATTERN.findall(source))
    if not ids:
        raise RuntimeError("CARD_LIBRARYのIDを抽出できません")
    return ids


def collect_art(valid_ids: set[str]) -> tuple[dict[str, Path], list[str]]:
    ART_DIRECTORY.mkdir(parents=True, exist_ok=True)
    art: dict[str, Path] = {}
    errors: list[str] = []
    for path in sorted(ART_DIRECTORY.iterdir(), key=lambda item: item.name.casefold()):
        if not path.is_file() or path.name == ".gitkeep":
            continue
        suffix = path.suffix.lower()
        card_id = path.stem
        if suffix not in ALLOWED_EXTENSIONS:
            errors.append(f"未対応拡張子: {path.name}")
            continue
        if not SAFE_STEM_PATTERN.fullmatch(card_id):
            errors.append(f"ファイル名はカードIDそのものにする: {path.name}")
            continue
        if card_id not in valid_ids:
            errors.append(f"カードリストに存在しないID: {path.name}")
            continue
        if card_id in art:
            errors.append(f"同一IDの画像が重複: {art[card_id].name}, {path.name}")
            continue
        art[card_id] = path
    return art, errors


def module_text(art: dict[str, Path]) -> str:
    rows = ["// Generated by scripts/sync-card-art.py. Do not edit by hand.", "export const CARD_ART = Object.freeze({"]
    for card_id, path in sorted(art.items()):
        relative = f"../assets/card-art/{path.name}"
        rows.append(f'  "{card_id}": new URL("{relative}", import.meta.url).href,')
    rows.extend(["});", ""])
    return "\n".join(rows)


def main() -> int:
    parser = argparse.ArgumentParser(description="カード画像をID検査してフロント用対応表を生成")
    parser.add_argument("--check", action="store_true", help="生成済み対応表が最新かだけ確認")
    args = parser.parse_args()
    try:
        ids = library_ids()
        art, errors = collect_art(ids)
        if errors:
            for error in errors:
                print(error, file=sys.stderr)
            return 2
        expected = module_text(art)
        current = GENERATED_MODULE.read_text(encoding="utf-8") if GENERATED_MODULE.exists() else ""
        if args.check and current != expected:
            print("card-art.generated.jsが画像フォルダと一致しません。--checkなしで再生成してください", file=sys.stderr)
            return 3
        if not args.check:
            GENERATED_MODULE.write_text(expected, encoding="utf-8", newline="\n")
        print(json.dumps({"cardArt": len(art), "libraryIds": len(ids), "check": args.check, "ok": True}, ensure_ascii=False))
        return 0
    except (OSError, RuntimeError) as error:
        print(str(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
